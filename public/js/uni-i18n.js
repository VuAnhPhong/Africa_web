/**
 * Switch language function: updates DOM elements and persists preference.
 */
function setLanguage(lang) {
    if (!['vi', 'en'].includes(lang)) lang = 'vi';
    localStorage.setItem('africa_lang', lang);
    document.cookie = `africa_lang=${lang};path=/;max-age=31536000`;
    document.documentElement.lang = lang;

    // Update active class on switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    const dict = window.i18nData[lang] || window.i18nData.vi;

    // 1. Text & HTML content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 2. Placeholders
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // 3. Title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (dict[key] !== undefined) {
            el.setAttribute('title', dict[key]);
        }
    });

    // Update dynamic skew slider active text if present
    const skewTitle = document.getElementById('skewSliderTitle');
    const skewDesc = document.getElementById('skewSliderDesc');
    if (skewTitle && skewDesc && !skewTitle.dataset.customHover) {
        skewTitle.textContent = dict['skew_header_title'] || 'Dịch vụ Logistics & Xuất Nhập Khẩu';
        skewDesc.textContent = dict['skew_header_desc'] || 'Cung cấp các giải pháp xuất nhập khẩu chuyên nghiệp đáp ứng nhu cầu khắt khe của từng doanh nghiệp';
    }
}

// Initialize on DOM ready
document.addEventListener('DOMContentLoaded', () => {
    // Read saved language from localStorage or default to 'vi'
    const savedLang = localStorage.getItem('africa_lang') || 'vi';

    // Bind click events on switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const chosenLang = btn.getAttribute('data-lang');
            setLanguage(chosenLang);
        });
    });

    // Apply language on load
    setLanguage(savedLang);
});
